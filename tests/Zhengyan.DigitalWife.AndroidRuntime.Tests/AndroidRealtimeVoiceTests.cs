    internal static void TestResponseAndSpeech()
    {
        using Fixture fixture = new();
        string request = fixture.Api.StartResponse(fixture.Entity, "question", requestId: "response-test",
            onDeltaCallback: "voice_delta", onCompletedCallback: "voice_done", onErrorCallback: "voice_error");
        fixture.Until(() => fixture.Player.Chunks.Count > 0);
        Check(request == "response-test" && fixture.Events.All(value => value.EventName != "completed"), "Response completed before audio playback drained.");
        fixture.Player.FinishPlayback();
        fixture.Until(() => fixture.Events.Any(value => value.EventName == "completed"));
        var deltas = fixture.Events.Where(value => value.EventName == "delta" && value.Delta.Length > 0).ToArray();
        Check(deltas.Select(value => value.Delta).SequenceEqual(["server ", "reply"]), "Response deltas were not generated by the server.");
        Check(deltas[0].Text == "question" && deltas[1].AccumulatedText == "server reply" && deltas.All(value => value.CallbackName == "voice_delta" && !value.IsFinal), "Realtime delta fields differ from desktop.");
        RuntimeRealtimeVoiceScriptEvent done = fixture.Events.Last();
        Check(done.Text == "server reply" && done.AccumulatedText == done.Text && done.RecognizedText == "question"
            && done.CallbackName == "voice_done" && done.IsFinal, "Response completion fields differ from desktop.");
        Check(fixture.Player.Chunks.Single().Samples.Span[0] > .24f && fixture.Player.Chunks.Single().Samples.Span[0] < .26f, "Project output volume was ignored.");
        fixture.Server.VerifySession();
        Check(fixture.Server.Requests.Any(value => value.Type == "conversation.item.create" && value.Item!.Content.Single().Text == "question"), "User text was not inserted into the service conversation.");

        fixture.Events.Clear();
        fixture.Player.ResetPlayback();
        fixture.Api.StartSpeakText(fixture.Entity, "prompt", requestId: "speech-test", onCompletedCallback: "prompt_done", onErrorCallback: "voice_error");
        fixture.Until(() => fixture.Player.LastAudio is not null);
        Check(fixture.Events.Count == 0, "Speech completion fired when synthesis finished instead of playback.");
        fixture.Player.FinishPlayback();
        fixture.Until(() => fixture.Events.Count > 0);
        Check(fixture.Events.Single().EventName == "speech_completed" && fixture.Events[0].CallbackName == "prompt_done" && fixture.Events[0].RequestId == "speech-test", "Speech completion event or request ID was lost.");
        JsonElement speech = fixture.Server.SpeechRequests.Single();
        Check(speech.GetProperty("input").GetString() == "prompt" && speech.GetProperty("model").GetString() == "test-model"
            && speech.GetProperty("voice").GetString() == "test-voice" && Math.Abs(speech.GetProperty("speed").GetSingle() - 1.7f) < .001f
            && speech.GetProperty("response_format").GetString() == "wav", "Speech did not use project model, voice, speed or format.");
        Check(fixture.Server.HttpPaths.Single() == "/voice/speech", "Speech HTTP path ignored project configuration.");
        Check(fixture.Player.LastAudio!.Samples[0] > .24f && fixture.Player.LastAudio.Samples[0] < .26f, "Speech ignored project output volume.");
    }

    internal static void TestTranscriptionAndConversation()
    {
        using Fixture fixture = new();
        fixture.Server.Transcripts.Enqueue("");
        fixture.Server.Transcripts.Enqueue("heard text");
        fixture.Api.StartTranscription(fixture.Entity, requestId: "transcribe-test", timeoutSeconds: 3,
            onCompletedCallback: "voice_transcribed", onTimeoutCallback: "voice_timeout", onErrorCallback: "voice_error");
        fixture.Until(() => fixture.Events.Any(value => value.EventName == "transcription_completed"));
        RuntimeRealtimeVoiceScriptEvent transcribed = fixture.Events.Single();
        Check(transcribed.Text == "heard text" && transcribed.AccumulatedText == transcribed.Text && transcribed.RecognizedText == transcribed.Text
            && transcribed.RequestId == "transcribe-test" && transcribed.CallbackName == "voice_transcribed", "Server transcription fields differ from desktop.");
        Check(fixture.Source.RecordCount == 2 && fixture.Server.Requests.Count(value => value.Type == "input_audio_buffer.commit") == 2, "Empty transcripts were not retried.");
        Check(fixture.Source.LastOptions?.SampleRate == 16000 && fixture.Source.LastOptions.Channels == 1, "Transcription ignored project capture settings.");
        Check(fixture.Server.Deleted.Contains("audio-1"), "Empty transcription item was not deleted.");

        fixture.Events.Clear();
        fixture.Player.FinishPlayback();
        fixture.Api.StartResponse(fixture.Entity, "heard text", onCompletedCallback: "voice_done", onErrorCallback: "voice_error");
        fixture.Until(() => fixture.Events.Any(value => value.EventName == "completed"));
        Check(!fixture.Server.Requests.Any(value => value.Type == "conversation.item.create"), "Matching transcript was duplicated as a user text item.");

        fixture.Events.Clear();
        fixture.Server.Transcripts.Enqueue("original text");
        fixture.Api.StartTranscription(fixture.Entity, timeoutSeconds: 3, onCompletedCallback: "voice_transcribed", onErrorCallback: "voice_error");
        fixture.Until(() => fixture.Events.Any(value => value.EventName == "transcription_completed"));
        fixture.Events.Clear();
        fixture.Api.StartResponse(fixture.Entity, "edited text", onCompletedCallback: "voice_done", onErrorCallback: "voice_error");
        fixture.Until(() => fixture.Events.Any(value => value.EventName == "completed"));
        Check(fixture.Server.Deleted.Contains("audio-3") && fixture.Server.Requests.Any(value => value.Item?.Content.FirstOrDefault()?.Text == "edited text"), "Edited transcript did not replace its service conversation item.");
        Task reset = fixture.Api.ResetConversationAsync();
        fixture.Until(() => reset.IsCompleted);
        reset.GetAwaiter().GetResult();
        Check(fixture.Server.Deleted.Contains("audio-2") && fixture.Server.Deleted.Contains("user-1"), "Conversation reset did not delete retained service items.");
    }

    internal static void TestTimeoutCancellationAndErrors()
    {
        using Fixture fixture = new();
        fixture.Source.WaitForCancellation = true;
        fixture.Api.StartTranscription(fixture.Entity, timeoutSeconds: .05f, onTimeoutCallback: "voice_timeout", onErrorCallback: "voice_error");
        fixture.Until(() => fixture.Events.Count > 0);
        Check(fixture.Events.Single().EventName == "timeout" && fixture.Events[0].CallbackName == "voice_timeout", "Capture deadline was not reported as a timeout.");

        fixture.Events.Clear();
        int previous = fixture.Source.RecordCount;
        string canceled = fixture.Api.StartTranscription(fixture.Entity, timeoutSeconds: 10, onCompletedCallback: "done", onErrorCallback: "failed");
        fixture.Until(() => fixture.Source.RecordCount > previous);
        fixture.Api.CancelRequest(canceled);
        fixture.PumpFor(100);
        Check(fixture.Events.Count == 0, "Canceled transcription generated callbacks.");

        fixture.Source.WaitForCancellation = false;
        fixture.Server.ResponseError = "test backend failure";
        fixture.Api.StartResponse(fixture.Entity, "test", requestId: "error-test", onErrorCallback: "voice_error");
        fixture.Until(() => fixture.Events.Count > 0);
        Check(fixture.Events.Single().EventName == "error" && fixture.Events[0].CallbackName == "voice_error"
            && fixture.Events[0].Error.Contains("test backend failure"), "Service error was not forwarded to the script.");
        Check(global::Android.Util.Log.Entries.Any(value => value.Level == "error" && value.Message.Contains("error-test")), "Realtime service error did not reach Android logs.");

        fixture.Server.ResponseError = null;
        fixture.Events.Clear();
        fixture.Player.ResetPlayback();
        fixture.Api.StartResponse(fixture.Entity, "stale", onCompletedCallback: "stale_done", onErrorCallback: "stale_error");
        fixture.Until(() => fixture.Player.Chunks.Count > 0);
        fixture.Runtime.ClearScene();
        fixture.Events.Clear();
        fixture.Player.FinishPlayback();
        fixture.PumpFor(100);
        Check(fixture.Events.Count == 0, "A cleared scene received a late response or playback callback.");
    }

