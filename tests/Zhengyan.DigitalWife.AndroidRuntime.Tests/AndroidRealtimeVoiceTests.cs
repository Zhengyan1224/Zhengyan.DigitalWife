        internal void Until(Func<bool> condition)
        {
            DateTime deadline = DateTime.UtcNow.AddSeconds(10);
            while (!condition())
            {
                Dispatcher.Pump();
                if (Server.Failure is { } failure) throw new Exception("Fake service failed.", failure);
                if (DateTime.UtcNow > deadline) throw new TimeoutException(string.Join("\n", Events.Select(value => value.Error)));
                Thread.Sleep(1);
            }
            Dispatcher.Pump();
        }
        internal void PumpFor(int milliseconds)
        {
            DateTime end = DateTime.UtcNow.AddMilliseconds(milliseconds);
