    internal static void TestWakeWordAndCapture()
    {
        using Fixture fixture = new();
        fixture.Settings.WakeWord.Enabled = true;
        fixture.Server.Transcripts.Enqueue("unrelated words");
        fixture.Server.Transcripts.Enqueue("小");
        fixture.Server.Transcripts.Enqueue("小雨，今天天气");
        fixture.Api.StartWakeWordMonitoring(fixture.Entity, "wake_word_hit", "wake_word_error");
        fixture.Until(() => fixture.Events.Any(value => value.EventName == "wake_word_detected"));
        fixture.Api.StopWakeWordMonitoring();
        RuntimeRealtimeVoiceScriptEvent hit = fixture.Events.First(value => value.EventName == "wake_word_detected");
        Check(hit.WakeWord == "小雨" && hit.Text == "今天天气" && hit.RecognizedText == "小雨，今天天气" && hit.CallbackName == "wake_word_hit", "Wake-word filtering, extension or tail extraction differs from desktop.");
        Check(fixture.Server.Requests.Count(value => value.Type == "input_audio_buffer.commit") >= 3, "Wake-word audio was not transcribed by the service.");

        ScriptedCapture source = new();
        source.Buffers.Enqueue([0, 0]);
        source.Buffers.Enqueue([.5f, .5f]);
        source.Buffers.Enqueue([0, 0]);
        source.Buffers.Enqueue([0, 0]);
        VoiceActivityCaptureOptions options = new() { SampleRate = 10, Channels = 1, PreRoll = TimeSpan.FromSeconds(.2), MinDuration = TimeSpan.FromSeconds(.4), MaxDuration = TimeSpan.FromSeconds(2), SilenceTimeout = TimeSpan.FromSeconds(.4), SilenceThreshold = .1f };
        AudioData audio = AndroidVoiceCapture.RecordUntilSilenceAsync(source, options, CancellationToken.None).GetAwaiter().GetResult();
        Check(audio.Samples.SequenceEqual(new float[] { 0, 0, .5f, .5f, 0, 0, 0, 0 }), "Native VAD lost pre-roll, speech or trailing silence.");
        using CancellationTokenSource canceled = new();
        canceled.Cancel();
        try { AndroidVoiceCapture.RecordUntilSilenceAsync(source, options, canceled.Token).GetAwaiter().GetResult(); throw new Exception("Canceled capture completed."); }
        catch (OperationCanceledException) { }
    }

