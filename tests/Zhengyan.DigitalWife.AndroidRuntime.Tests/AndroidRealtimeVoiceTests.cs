    private sealed class FakeSource : IAudioSource, IDisposable
    {
        internal bool WaitForCancellation;
        internal int RecordCount;
        internal VoiceActivityCaptureOptions? LastOptions;
        public async IAsyncEnumerable<AudioChunk> CaptureAsync(AudioCaptureOptions options, [EnumeratorCancellation] CancellationToken cancellationToken = default)
        {
            while (true)
            {
                await Task.Delay(5, cancellationToken);
                yield return new(Enumerable.Repeat(.1f, 1600).ToArray(), new(options.SampleRate, options.Channels), TimeSpan.Zero);
            }
        }
        public Task<AudioData> RecordAsync(TimeSpan duration, AudioCaptureOptions? options = null, CancellationToken cancellationToken = default)
            => AndroidVoiceCapture.RecordAsync(this, duration, options ?? new(), cancellationToken);
        public async Task<AudioData> RecordUntilSilenceAsync(VoiceActivityCaptureOptions? options = null, CancellationToken cancellationToken = default)
        {
            LastOptions = options;
            Interlocked.Increment(ref RecordCount);
            if (WaitForCancellation) await Task.Delay(Timeout.Infinite, cancellationToken);
            return new(Enumerable.Repeat(.1f, 1600).ToArray(), new(options!.SampleRate, options.Channels));
        }
        public void Dispose() { }
    }

    private sealed class ScriptedCapture : IAudioSource
    {
        internal Queue<float[]> Buffers { get; } = new();
        public async IAsyncEnumerable<AudioChunk> CaptureAsync(AudioCaptureOptions options, [EnumeratorCancellation] CancellationToken cancellationToken = default)
        {
            while (Buffers.TryDequeue(out float[]? samples))
            {
                cancellationToken.ThrowIfCancellationRequested();
                yield return new(samples, new(options.SampleRate, options.Channels), TimeSpan.Zero);
                await Task.Yield();
            }
        }
        public Task<AudioData> RecordAsync(TimeSpan duration, AudioCaptureOptions? options = null, CancellationToken cancellationToken = default) => throw new NotSupportedException();
        public Task<AudioData> RecordUntilSilenceAsync(VoiceActivityCaptureOptions? options = null, CancellationToken cancellationToken = default) => throw new NotSupportedException();
    }

    private sealed class FakePlayer : IAudioPlayer, IDisposable
    {
        private TaskCompletionSource<bool> _finish = new(TaskCreationOptions.RunContinuationsAsynchronously);
        internal ConcurrentQueue<AudioChunk> Chunks { get; } = new();
        internal AudioData? LastAudio;
        internal void FinishPlayback() => _finish.TrySetResult(true);
        internal void ResetPlayback() { _finish = new(TaskCreationOptions.RunContinuationsAsynchronously); Chunks.Clear(); LastAudio = null; }
        public async Task PlayAsync(AudioData audio, CancellationToken cancellationToken = default)
        {
            LastAudio = audio;
            await _finish.Task.WaitAsync(cancellationToken);
        }
        public async Task PlayAsync(IAsyncEnumerable<AudioChunk> audioStream, AudioFormat format, CancellationToken cancellationToken = default)
        {
            await foreach (AudioChunk chunk in audioStream.WithCancellation(cancellationToken)) Chunks.Enqueue(chunk);
            await _finish.Task.WaitAsync(cancellationToken);
        }
        public Task PlayFileAsync(string path, CancellationToken cancellationToken = default) => throw new NotSupportedException();
        public void Dispose() => FinishPlayback();
    }

    private sealed class LocalService : IDisposable
    {
        private readonly TcpListener _listener = new(IPAddress.Loopback, 0);
        private readonly CancellationTokenSource _lifetime = new();
        private readonly Task _accept;
        internal ConcurrentQueue<OpenAiRealtimeClientEvent> Requests { get; } = new();
        internal ConcurrentQueue<JsonElement> SpeechRequests { get; } = new();
        internal ConcurrentQueue<string> HttpPaths { get; } = new();
        internal ConcurrentQueue<string> Transcripts { get; } = new();
        internal ConcurrentBag<string> Deleted { get; } = [];
        internal string? ResponseError;
        internal Exception? Failure;
        internal string BaseUrl { get; }
        private OpenAiRealtimeSession _session = new();
        private int _audioId;
        private int _userId;

        internal LocalService()
        {
            _listener.Start();
            BaseUrl = "http://127.0.0.1:" + ((IPEndPoint)_listener.LocalEndpoint).Port;
            _accept = Task.Run(async () =>
            {
                try
                {
                    while (!_lifetime.IsCancellationRequested)
                    {
                        TcpClient client = await _listener.AcceptTcpClientAsync(_lifetime.Token);
                        _ = Handle(client);
                    }
                }
                catch (OperationCanceledException) { }
            });
        }
        private async Task Handle(TcpClient client)
        {
            using (client)
            {
                try
                {
                    await using NetworkStream stream = client.GetStream();
                    List<byte> header = [];
                    byte[] single = new byte[1];
                    while (true)
                    {
                        await stream.ReadExactlyAsync(single, _lifetime.Token);
                        header.Add(single[0]);
                        if (header.Count >= 4 && header.TakeLast(4).SequenceEqual(new byte[] { 13, 10, 13, 10 })) break;
                    }
                    string[] lines = Encoding.ASCII.GetString(header.ToArray()).Split("\r\n");
                    string path = lines[0].Split(' ')[1];
                    Dictionary<string, string> headers = lines.Skip(1).Where(line => line.Contains(':')).ToDictionary(line => line[..line.IndexOf(':')], line => line[(line.IndexOf(':') + 1)..].Trim(), StringComparer.OrdinalIgnoreCase);
                    Check(headers.GetValueOrDefault("Authorization") == "Bearer test-only", "Realtime transport lost the project API key.");
                    if (headers.TryGetValue("Sec-WebSocket-Key", out string? key))
                    {
                        Check(path.StartsWith("/voice/realtime?model=test-model"), "Realtime WebSocket endpoint ignored configuration.");
                        string accept = Convert.ToBase64String(SHA1.HashData(Encoding.ASCII.GetBytes(key + "258EAFA5-E914-47DA-95CA-C5AB0DC85B11")));
                        await stream.WriteAsync(Encoding.ASCII.GetBytes($"HTTP/1.1 101 Switching Protocols\r\nUpgrade: websocket\r\nConnection: Upgrade\r\nSec-WebSocket-Accept: {accept}\r\n\r\n"), _lifetime.Token);
                        using WebSocket socket = WebSocket.CreateFromStream(stream, true, null, Timeout.InfiniteTimeSpan);
                        await RunSocket(socket);
                    }
                    else
                    {
                        HttpPaths.Enqueue(path);
                        byte[] body = await ReadBody(stream, headers);
                        using JsonDocument payload = JsonDocument.Parse(body);
                        SpeechRequests.Enqueue(payload.RootElement.Clone());
                        using MemoryStream wav = new();
                        await WaveFile.WriteAsync(wav, new(Enumerable.Repeat(.5f, 2400).ToArray(), new(24000, 1)), cancellationToken: _lifetime.Token);
                        byte[] data = wav.ToArray();
                        await stream.WriteAsync(Encoding.ASCII.GetBytes($"HTTP/1.1 200 OK\r\nContent-Type: audio/wav\r\nContent-Length: {data.Length}\r\nConnection: close\r\n\r\n"), _lifetime.Token);
                        await stream.WriteAsync(data, _lifetime.Token);
                    }
                }
                catch (Exception ex) when (_lifetime.IsCancellationRequested || ex is WebSocketException or EndOfStreamException) { }
                catch (Exception ex) { Failure = ex; }
            }
        }
        private async Task RunSocket(WebSocket socket)
        {
            await Send(socket, new { type = "session.created", session = _session });
            byte[] buffer = new byte[65536];
            while (!_lifetime.IsCancellationRequested)
            {
                using MemoryStream message = new();
                WebSocketReceiveResult received;
                do
                {
                    received = await socket.ReceiveAsync(buffer, _lifetime.Token);
                    if (received.MessageType == WebSocketMessageType.Close)
                    {
                        await socket.CloseOutputAsync(WebSocketCloseStatus.NormalClosure, "close", _lifetime.Token);
                        return;
                    }
                    message.Write(buffer, 0, received.Count);
                } while (!received.EndOfMessage);
                OpenAiRealtimeClientEvent value = OpenAiRealtimeProtocol.DeserializeClientEvent(Encoding.UTF8.GetString(message.ToArray()));
                Requests.Enqueue(value);
                switch (value.Type)
                {
                    case "session.update":
                        _session = value.Session!;
                        await Send(socket, new { type = "session.updated", session = _session });
                        break;
                    case "conversation.item.create":
                        value.Item!.Id = "user-" + ++_userId;
                        await Send(socket, new { type = "conversation.item.created", item = value.Item });
                        break;
                    case "input_audio_buffer.commit":
                        string id = "audio-" + ++_audioId;
                        string text = Transcripts.TryDequeue(out string? transcript) ? transcript : "heard text";
                        await Send(socket, new { type = "input_audio_buffer.committed", item_id = id });
                        await Send(socket, new { type = "conversation.item.created", item = new { id, role = "user", type = "message", content = new[] { new { type = "input_audio", transcript = text } } } });
                        await Send(socket, new { type = "conversation.item.input_audio_transcription.completed", item_id = id, transcript = text });
                        break;
                    case "conversation.item.delete":
                        Deleted.Add(value.ItemId!);
                        await Send(socket, new { type = "conversation.item.deleted", item_id = value.ItemId });
                        break;
                    case "response.create":
                        if (ResponseError is { } error)
                        {
                            await Send(socket, new { type = "error", error = new { message = error, code = "test_error" } });
                            break;
                        }
                        await Send(socket, new { type = "response.created", response = new { id = "response" } });
                        await Send(socket, new { type = "response.output_audio_transcript.delta", delta = "server " });
                        await Send(socket, new { type = "response.output_audio_transcript.delta", delta = "reply" });
                        string audio = OpenAiRealtimeProtocol.EncodePcm16(new(Enumerable.Repeat(.5f, 2400).ToArray(), new(24000, 1)), OpenAiRealtimeAudioFormat.Pcm16());
                        await Send(socket, new { type = "response.output_audio.delta", delta = audio });
                        await Send(socket, new { type = "response.done", response = new { id = "response", status = "completed" } });
                        break;
                }
            }
        }
        private Task Send(WebSocket socket, object value)
            => socket.SendAsync(Encoding.UTF8.GetBytes(JsonSerializer.Serialize(value)), WebSocketMessageType.Text, true, _lifetime.Token);

        private async Task<byte[]> ReadBody(Stream stream, Dictionary<string, string> headers)
        {
            if (headers.TryGetValue("Content-Length", out string? length))
            {
                byte[] body = new byte[int.Parse(length)];
                await stream.ReadExactlyAsync(body, _lifetime.Token);
                return body;
            }
            Check(headers.GetValueOrDefault("Transfer-Encoding") == "chunked", "Unexpected HTTP request framing.");
            using MemoryStream result = new();
            while (true)
            {
                string size = await ReadLine(stream);
                int count = Convert.ToInt32(size.Split(';')[0], 16);
                if (count == 0) { await ReadLine(stream); return result.ToArray(); }
                byte[] chunk = new byte[count];
                await stream.ReadExactlyAsync(chunk, _lifetime.Token);
                result.Write(chunk);
                Check(await ReadLine(stream) == "", "HTTP chunk terminator was missing.");
            }
        }

        private async Task<string> ReadLine(Stream stream)
        {
            List<byte> bytes = [];
            byte[] buffer = new byte[1];
            while (true)
            {
                await stream.ReadExactlyAsync(buffer, _lifetime.Token);
                if (buffer[0] == 10) return Encoding.ASCII.GetString(bytes.ToArray()).TrimEnd('\r');
                bytes.Add(buffer[0]);
            }
        }
        internal void VerifySession()
        {
            Check(_session.Model == "test-model" && _session.Instructions == "test instructions" && _session.Audio.Output.Voice == "test-voice", "Realtime session model, instructions or voice ignored project settings.");
            Check(_session.Audio.Input.Format.Rate == 16000 && _session.Audio.Output.Format.Rate == 24000
                && _session.Audio.Input.Transcription?.Language == "zh" && _session.Audio.Input.Transcription.Prompt == "test prompt"
                && _session.Audio.Input.TurnDetection is null, "Realtime session audio/transcription settings differ from desktop.");
        }
        public void Dispose() { _lifetime.Cancel(); _listener.Stop(); _accept.GetAwaiter().GetResult(); }
    }

    private static void Check(bool condition, string message)
    {
        if (!condition) throw new InvalidOperationException(message);
    }
